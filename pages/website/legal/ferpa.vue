        <h2>1. Introduction to FERPA</h2>
        <p>
          The Family Educational Rights and Privacy Act (FERPA) is a federal privacy law that protects the privacy of student education records. FERPA applies to all schools that receive funds under an applicable program of the U.S. Department of Education.
        </p>
        <p>
          As an educational technology provider serving schools and universities, Classsemble is committed to full compliance with FERPA requirements and protecting student educational records in accordance with federal law.
        </p>

        <h2>2. Our FERPA Responsibilities</h2>
        
        <h3>2.1 School Official Status</h3>
        <p>
          Classsemble operates as a "school official" under FERPA when:
        </p>
        <ul>
          <li>We perform an institutional service or function for which the school would otherwise use employees</li>
          <li>We are under the direct control of the educational institution regarding use and maintenance of education records</li>
          <li>We are subject to the same conditions governing the use and redisclosure of personally identifiable information</li>
          <li>We have a legitimate educational interest in the education records</li>
        </ul>

        <h3>2.2 Legitimate Educational Interest</h3>
        <p>
          Our legitimate educational interest includes:
        </p>
        <ul>
          <li>Facilitating course collaboration and communication</li>
          <li>Enabling meeting scheduling for educational purposes</li>
          <li>Supporting instructor-student and peer-to-peer academic interactions</li>
          <li>Providing analytics to improve educational outcomes</li>
          <li>Ensuring platform security and data protection</li>
        </ul>

        <h2>3. Student Education Records</h2>
        
        <h3>3.1 What Constitutes Education Records</h3>
        <p>
          Under FERPA, education records include records that:
        </p>
        <ul>
          <li>Are directly related to a student</li>
          <li>Are maintained by an educational agency or institution</li>
          <li>Contain personally identifiable information</li>
        </ul>
        
        <h3>3.2 FERPA-Protected Information in Our Platform</h3>
        <ul>
          <li><strong>Student Identifiers:</strong> Names, student ID numbers, email addresses</li>
          <li><strong>Course Enrollment:</strong> Course participation, enrollment status</li>
          <li><strong>Academic Communications:</strong> Messages, discussions, meeting participation</li>
          <li><strong>Engagement Data:</strong> Platform usage, participation analytics</li>
          <li><strong>Collaborative Work:</strong> Group project participation, meeting attendance</li>
        </ul>

        <h3>3.3 Information NOT Covered by FERPA</h3>
        <ul>
          <li>Sole possession records kept by instructors for personal use</li>
          <li>Law enforcement records maintained separately</li>
          <li>Alumni records that don't relate to the person as a student</li>
          <li>Public directory information (if properly designated)</li>
        </ul>

        <h2>4. Access and Disclosure Controls</h2>
        
        <h3>4.1 Permitted Disclosures Without Consent</h3>
        <p>
          We may disclose student education records without written consent only to:
        </p>
        <ul>
          <li><strong>School Officials:</strong> Institutional personnel with legitimate educational interest</li>
          <li><strong>Other Schools:</strong> Where student seeks enrollment (with proper procedures)</li>
          <li><strong>Authorized Representatives:</strong> For audit, evaluation, or compliance purposes</li>
          <li><strong>Financial Aid Officials:</strong> For determining aid eligibility</li>
          <li><strong>Organizations Conducting Studies:</strong> For educational agencies (with strict controls)</li>
          <li><strong>Accrediting Organizations:</strong> For accreditation functions</li>
          <li><strong>Legal Compliance:</strong> To comply with judicial order or subpoena</li>
          <li><strong>Health/Safety Emergency:</strong> To protect health or safety</li>
        </ul>

        <h3>4.2 Written Consent Requirements</h3>
        <p>
          When written consent is required, it must specify:
        </p>
        <ul>
          <li>Records to be disclosed</li>
          <li>Purpose of the disclosure</li>
          <li>Party to whom disclosure may be made</li>
          <li>Student's signature and date</li>
        </ul>

        <h2>5. Student Rights Under FERPA</h2>
        
        <h3>5.1 Right to Inspect and Review</h3>
        <p>
          Students have the right to:
        </p>
        <ul>
          <li>Inspect and review their education records within 45 days of request</li>
          <li>Receive copies of records (fees may apply)</li>
          <li>Have records explained or interpreted by school officials</li>
          <li>Receive a list of types and locations of education records</li>
        </ul>

        <h3>5.2 Right to Request Amendment</h3>
        <p>
          Students may request amendment of education records they believe are:
        </p>
        <ul>
          <li>Inaccurate</li>
          <li>Misleading</li>
          <li>In violation of privacy rights</li>
        </ul>

        <h3>5.3 Right to Control Disclosures</h3>
        <p>
          Students have the right to:
        </p>
        <ul>
          <li>Consent to disclosures of personally identifiable information</li>
          <li>Prevent disclosure of directory information (with proper opt-out)</li>
          <li>Receive notice of disclosures to certain parties</li>
        </ul>

        <h3>5.4 Right to File Complaints</h3>
        <p>
          Students may file complaints with the Department of Education if they believe FERPA rights have been violated.
        </p>

        <h2>6. Our Technical Safeguards</h2>
        
